pub fn menu_vi(english: &str) -> Option<&'static str> {
    let normalized = english.trim().replace("...", "…");
    if let Some((key, _)) = EN.iter().find(|(_, value)| value.eq_ignore_ascii_case(&normalized)) {
        if let Some((_, vi)) = VI.iter().find(|(candidate, _)| candidate == key) {
            return Some(vi);
        }
    }
    APP_MENU_VI.iter().find(|(key, _)| key.eq_ignore_ascii_case(&normalized)).map(|(_, vi)| *vi)
}

pub fn day_period(lang: Lang, hour: u32) -> &'static str {
    match (lang, hour < 12) {
        (Lang::Vi, true) => "SA",
        (Lang::Vi, false) => "CH",
        (Lang::En, true) => "AM",
        (Lang::En, false) => "PM",
    }
}

pub fn is_known(src: &str) -> bool {
    EN.iter().any(|(k, en)| *k == src || *en == src)
}

pub fn tr(lang: Lang, src: &'static str) -> &'static str {
    match lang {
        Lang::En => EN.iter().find(|(k, _)| *k == src).map(|(_, v)| *v).unwrap_or(src),
        Lang::Vi => VI
            .iter()
            .find(|(k, _)| *k == src)
            .map(|(_, v)| *v)
            .or_else(|| {
                EN.iter()
                    .find(|(_, en)| *en == src)
                    .and_then(|(k, _)| VI.iter().find(|(vk, _)| vk == k).map(|(_, v)| *v))
            })
            .unwrap_or_else(|| tr(Lang::En, src)),
    }
}

pub fn month_name(lang: Lang, m: u32, fallback: &'static str) -> &'static str {
    match lang {
        Lang::En => {
            const N: [&str; 12] =
                ["January", "February", "March", "April", "May", "June", "July", "August", "September", "October", "November", "December"];
            N.get((m.max(1) - 1) as usize % 12).copied().unwrap_or(fallback)
        }
        Lang::Vi => {
            const N: [&str; 12] = [
                "Tháng 1", "Tháng 2", "Tháng 3", "Tháng 4", "Tháng 5", "Tháng 6", "Tháng 7", "Tháng 8", "Tháng 9",
                "Tháng 10", "Tháng 11", "Tháng 12",
            ];
            N.get((m.max(1) - 1) as usize % 12).copied().unwrap_or(fallback)
        }
    }
}

pub fn weekday_labels(lang: Lang, monday_first: bool, _fallback: [&'static str; 7]) -> [&'static str; 7] {
    match lang {
        Lang::En => {
            if monday_first {
                ["Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun"]
            } else {
                ["Sun", "Mon", "Tue", "Wed", "Thu", "Fri", "Sat"]
            }
        }
        Lang::Vi => {
            if monday_first {
                ["T2", "T3", "T4", "T5", "T6", "T7", "CN"]
            } else {
                ["CN", "T2", "T3", "T4", "T5", "T6", "T7"]
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn english_is_default_and_translates() {
        assert_eq!(Lang::default(), Lang::En);
        assert_eq!(tr(Lang::En, "Buka"), "Open");
        assert_eq!(tr(Lang::Vi, "Buka"), "Mở");
        assert_eq!(tr(Lang::En, "tidak ada"), "tidak ada");
    }

    #[test]
    fn vietnamese_translates_and_falls_back_to_english() {
        assert_eq!(tr(Lang::Vi, "Pengaturan"), "Cài đặt");
        assert_eq!(tr(Lang::Vi, "Ukuran Visor"), "Kích thước Breeze Notch");
        assert_eq!(tr(Lang::En, "Ukuran Visor"), "Breeze Notch size");
        assert_eq!(tr(Lang::Vi, "Lebar Notch"), "Chiều rộng Breeze Notch");
        assert_eq!(tr(Lang::Vi, "Tinggi Notch"), "Chiều cao Breeze Notch");
        assert_eq!(tr(Lang::Vi, "Ukuran Rail"), "Kích thước Upper Bar");
        assert_eq!(tr(Lang::Vi, "tidak ada"), "tidak ada");
        for (k, v) in EN.iter() {
            let vi = tr(Lang::Vi, k);
            assert!(VI.iter().any(|(e, _)| e == k) || vi == *v, "missing Vietnamese translation should fall back to English: {k}");
        }
    }

    #[test]
    fn no_duplicate_keys() {
        for table in [EN, VI] {
            for (i, (k, _)) in table.iter().enumerate() {
                assert!(!table[i + 1..].iter().any(|(k2, _)| k2 == k), "duplikat: {k}");
            }
        }
    }

    #[test]
    fn calendar_names() {
        assert_eq!(month_name(Lang::En, 11, "November"), "November");
        assert_eq!(month_name(Lang::En, 1, "Januari"), "January");
        assert_eq!(month_name(Lang::Vi, 11, "November"), "Tháng 11");
        assert_eq!(weekday_labels(Lang::En, true, [""; 7])[0], "Mon");
        assert_eq!(weekday_labels(Lang::Vi, true, [""; 7])[0], "T2");
    }
}
